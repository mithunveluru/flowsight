-- V16: merchant resolution. Additive only: the pg_trgm extension, a global alias table,
-- per-user merchant rules learned from corrections, and the raw merchant text on
-- transactions (nullable, no default, so existing rows are untouched).

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- Alias text is stored in match form (lower case, punctuation removed). Lower priority
-- wins when several aliases appear in one descriptor. Seeded from the built-in aliases
-- in MerchantNormalizationService; region NULL means global.
CREATE TABLE merchant_aliases (
    id             BIGSERIAL    PRIMARY KEY,
    alias          VARCHAR(120) NOT NULL,
    canonical_name VARCHAR(120) NOT NULL,
    canonical_key  VARCHAR(120) NOT NULL,
    region         VARCHAR(2),
    priority       INTEGER      NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_merchant_aliases_alias UNIQUE (alias)
);

CREATE INDEX idx_merchant_aliases_alias_trgm ON merchant_aliases USING gin (alias gin_trgm_ops);

-- One rule per user and grouping key: the merchant name and/or category the user chose.
CREATE TABLE user_merchant_rules (
    id             UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id        UUID         NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    match_key      VARCHAR(255) NOT NULL,
    canonical_name VARCHAR(255),
    category       VARCHAR(100),
    applied_count  INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_user_merchant_rules_user_key UNIQUE (user_id, match_key)
);

CREATE INDEX idx_user_merchant_rules_name_trgm ON user_merchant_rules USING gin (canonical_name gin_trgm_ops);

CREATE TRIGGER trg_user_merchant_rules_updated_at
    BEFORE UPDATE ON user_merchant_rules
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

ALTER TABLE transactions ADD COLUMN merchant_raw VARCHAR(255);

